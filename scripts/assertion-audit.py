#!/usr/bin/env python3
"""Per-skill audit from the saved compare results (no model calls).

For each skill: margin (with minus without, in assertions); per-assertion classes when compare-results rows carry
with_assert/without_assert (run `skill-eval.py assertjudge all` first): (a) pass only with the skill, (b) both pass,
(c) both fail, (d) pass only without; reference files never opened and always opened (from files_read);
tasks where the no-skill answer passed >= 85% (too easy, candidates to replace).
Writes docs/assertion-audit.json and docs/assertion-audit.md.
"""
import glob, json, os
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
out, md = {}, ["# Assertion and reference audit", "", "Generated by scripts/assertion-audit.py from skills/*/evals/compare-results.json.", ""]
for f in sorted(glob.glob(str(REPO / "skills" / "*" / "evals" / "compare-results.json"))):
    skill = Path(f).parts[-3]
    rows = json.load(open(f))["rows"]
    evs = {str(e["id"]): e for e in json.load(open(REPO / "skills" / skill / "evals" / "evals.json"))["evals"]}
    w = wo = tot = 0
    classes = {"a_only_with": [], "b_both": [], "c_both_fail": [], "d_only_without": []}
    easy, have = [], 0
    for r in rows:
        try:
            a, n = map(int, r["with_pass"].split("/")); b = int(r["without_pass"].split("/")[0])
        except Exception:
            continue
        w += a; wo += b; tot += n
        if n and b / n >= 0.85:
            easy.append(f'{r["id"]} ({b}/{n})')
        if r.get("with_assert") and r.get("without_assert"):
            have += 1
            for i, (x, y) in enumerate(zip(r["with_assert"], r["without_assert"])):
                txt = evs.get(str(r["id"]), {}).get("assertions", [""] * (i + 1))[i]
                key = "a_only_with" if x and not y else "b_both" if x and y else "c_both_fail" if not x and not y else "d_only_without"
                classes[key].append(f'{r["id"]}.{i+1}: {txt}')
    refs = sorted(os.path.relpath(p, REPO / "skills" / skill) for p in glob.glob(str(REPO / "skills" / skill / "references" / "**" / "*.md"), recursive=True)
                  if not p.endswith("BIBLIOGRAPHY.md"))
    reads = [set(x.split(skill + "/")[-1] for x in r.get("files_read", [])) for r in rows]
    opened = set().union(*reads) if reads else set()
    never = [x for x in refs if x not in opened]
    always = [x for x in refs if reads and all(x in s for s in reads)]
    out[skill] = {"margin": w - wo, "with": w, "without": wo, "of": tot, "tasks_with_per_assertion": have,
                  **{k: v for k, v in classes.items()}, "refs_never_opened": never, "refs_always_opened": always, "easy_tasks_85": easy}
ranked = sorted(out, key=lambda s: out[s]["margin"])
for s in ranked:
    o = out[s]
    md += [f"## {s}  margin {o['margin']} ({o['with']} vs {o['without']} of {o['of']})", "",
           f"- per-assertion data for {o['tasks_with_per_assertion']} tasks: a={len(o['a_only_with'])} b={len(o['b_both'])} c={len(o['c_both_fail'])} d={len(o['d_only_without'])}",
           f"- references never opened ({len(o['refs_never_opened'])}): {', '.join(o['refs_never_opened']) or '-'}",
           f"- references always opened: {', '.join(o['refs_always_opened']) or '-'}",
           f"- tasks where no-skill passed >= 85%: {', '.join(o['easy_tasks_85']) or '-'}", ""]
(REPO / "docs" / "assertion-audit.json").write_text(json.dumps(out, indent=1, ensure_ascii=False))
(REPO / "docs" / "assertion-audit.md").write_text("\n".join(md))
print("8 skills with the lowest margin:", ", ".join(f"{s} ({out[s]['margin']})" for s in ranked[:8]))
print("skills with per-assertion data:", sum(1 for s in out if out[s]["tasks_with_per_assertion"]))
print("references never opened, total:", sum(len(out[s]["refs_never_opened"]) for s in out), "in", sum(1 for s in out if out[s]["refs_never_opened"]), "skills")
print("too-easy tasks (no-skill >= 85%):", sum(len(out[s]["easy_tasks_85"]) for s in out))
